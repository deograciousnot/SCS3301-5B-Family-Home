function [fig, S] = create_figure(S)
% CREATE_FIGURE  Window, 3D axes and the on-screen controls (R7).
%
% Author(s): <MEMBER NAME>   |   SCS3301 Group XX, Project 5B
fig = figure('Name', 'SCS3301 - 5B Family Home', 'NumberTitle', 'off', ...
             'Color', [0.12 0.12 0.15], 'Position', [80 80 1200 700], ...
             'KeyPressFcn', @on_key_press);

ax = axes('Parent', fig, 'Position', [0 0.06 0.76 0.94]);
hold(ax, 'on');  axis(ax, 'equal');  axis(ax, 'off');
axis(ax, [-1 13 -1 7 -0.1 3.5]);

helpText = { 'CONTROLS', '', ...
    '1 / 2   open/close door 1 / door 2', ...
    'F       open/close fridge', ...
    'T       TV on/off', ...
    'K       cooker on/off', ...
    'L       lamps on/off', ...
    'N       night mode (challenge) on/off', ...
    'J       jump to 22:45 (demo night)', ...
    'C       next camera', ...
    'P       perspective / orthographic', ...
    '+ / -   faster / slower time', ...
    'Q       quit', '', ...
    'Time speed (hours per second):'};
uicontrol(fig, 'Style', 'text', 'Units', 'normalized', ...
    'Position', [0.77 0.40 0.22 0.56], 'String', helpText, ...
    'HorizontalAlignment', 'left', 'FontName', 'Consolas', 'FontSize', 10, ...
    'BackgroundColor', [0.12 0.12 0.15], 'ForegroundColor', [0.9 0.9 0.9]);

S.h.speedSlider = uicontrol(fig, 'Style', 'slider', 'Units', 'normalized', ...
    'Position', [0.78 0.36 0.20 0.03], 'Min', 0, 'Max', 2, ...
    'Value', S.hoursPerSecond, 'Callback', @on_speed_slider, ...
    'KeyPressFcn', @on_key_press);   % keys still work after clicking slider

S.h.status = uicontrol(fig, 'Style', 'text', 'Units', 'normalized', ...
    'Position', [0 0 1 0.05], 'String', '', 'FontSize', 11, ...
    'HorizontalAlignment', 'left', 'FontName', 'Consolas', ...
    'BackgroundColor', [0.05 0.05 0.07], 'ForegroundColor', [1 0.9 0.5]);

S.fig = fig;
S.ax  = ax;
end

function on_speed_slider(src, ~)
% Slider changes how fast the time of day passes (behaviour control, R7).
S = guidata(src);
S.hoursPerSecond = get(src, 'Value');
guidata(src, S);
end
